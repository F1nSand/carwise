"""Storage contracts shared by the JSON compatibility stores and SQLite runtime."""

from __future__ import annotations

from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class RunRepository(Protocol):
    def create_run(self, run_id: str, session_id: str, input_text: str, *, context_id: str | None = None, owner_id: str | None = None, request_data: dict[str, Any] | None = None, client_request_id: str | None = None, idempotency_operation: str = "submit") -> dict[str, Any]: ...
    def get_run(self, run_id: str) -> dict[str, Any]: ...
    def get_run_owned(self, run_id: str, owner_id: str) -> dict[str, Any]: ...
    def list_runs(self, session_id: str | None = None) -> list[dict[str, Any]]: ...
    def list_runs_owned(self, owner_id: str, session_id: str | None = None) -> list[dict[str, Any]]: ...
    def claim_start(self, run_id: str) -> bool: ...
    def append_run_event(self, run_id: str, event: dict[str, Any], *, lease_token: str | None = None) -> dict[str, Any] | None: ...
    def read_run_events(self, run_id: str, after_seq: int = 0, limit: int = 200) -> list[dict[str, Any]]: ...
    def pause_run(self, run_id: str, checkpoint: dict[str, Any], pending_input: dict[str, Any], runtime: dict[str, Any] | None = None, result: dict[str, Any] | None = None, *, waiting_event: dict[str, Any] | None = None, session_messages: list[dict[str, Any]] | None = None, session_run_id: str | None = None, lease_token: str | None = None) -> dict[str, Any] | None: ...
    def finish_run(self, run_id: str, result: dict[str, Any] | None = None, error: str | None = None, *, lease_token: str | None = None, failure_code: str | None = None, retryable: bool = False) -> dict[str, Any] | None: ...
    def complete_run(self, run_id: str, result: dict[str, Any] | None = None, *, error: str | None = None, failure_code: str | None = None, retryable: bool = False, session_messages: list[dict[str, Any]] | None = None, session_run_id: str | None = None, lease_token: str | None = None) -> dict[str, Any] | None: ...
    def reconcile_runs(self, *, now_iso: str | None = None) -> list[dict[str, Any]]: ...


@runtime_checkable
class SessionRepository(Protocol):
    def load_session(self, session_id: str) -> Any: ...
    def load_session_owned(self, session_id: str, owner_id: str) -> Any: ...
    def append_session_messages(self, session_id: str, messages: list[dict[str, Any]], *, run_id: str | None = None, owner_id: str | None = None, lease_token: str | None = None) -> Any: ...
    def rollback_session(self, session_id: str, message_id: str, *, expected_revision: int | None = None, owner_id: str | None = None) -> Any: ...
    def active_session_records(self, session_id: str) -> list[dict[str, Any]]: ...


@runtime_checkable
class ConversationRepository(Protocol):
    def create_conversation(self, owner_id: str, command_id: str) -> dict[str, Any]: ...
    def accept_conversation_message(self, conversation_id: str, *, owner_id: str, command_id: str, content: str, source_report_id: str | None = None, allow_steering: bool = True) -> dict[str, Any]: ...
    def get_conversation_owned(self, conversation_id: str, owner_id: str) -> dict[str, Any]: ...
    def list_conversations_owned(self, owner_id: str, *, cursor: str | None = None, limit: int = 30) -> dict[str, Any]: ...
    def list_conversation_entries_owned(self, conversation_id: str, owner_id: str, *, before_seq: int | None = None, limit: int = 50) -> dict[str, Any]: ...
